/**
 * Hoe een random forest tot zijn antwoord komt: veel kleine bomen, elk op een
 * willekeurig stuk van de train set, en dan stemmen.
 *
 * Dit bestand is de rekenkant van het bord "Het bos stemt" (les 6). Het weet
 * niets over pixels of kleuren. De tekening staat in src/demos/StemmendBos.tsx.
 *
 * ------------------------------------------------------------------------
 * WAT HET BORD UITLEGT, IN DE WOORDEN VAN DE LES
 * ------------------------------------------------------------------------
 *
 *   2132676  "aan de hand van een willekeurig (= random) gekozen stuk van de
 *            train set wordt een boom gemaakt die vaak ook enkel gebruik maken
 *            van een aantal willekeurige (= random) kenmerken"
 *   2132681  "Democratie dus: de winnaar is wie het meeste stemmen krijgt."
 *
 * Dus precies twee keer toeval en één stemming, en niets anders:
 *   1. elke boom trekt 200 keer een willekeurige rij uit de train set (met
 *      teruglegging, zoals `RandomForestClassifier` met `bootstrap=True`);
 *   2. elk vakje kijkt naar één willekeurig kenmerk (`max_features='sqrt'`, en
 *      de wortel van 2 kenmerken is 1);
 *   3. voor een nieuwe boeking volgt elke boom zijn condities tot een blad, en
 *      de klasse met de meeste stemmen wint (de harde stemming van 2132681).
 *
 * ------------------------------------------------------------------------
 * DE DATA: DE LES ZELF, hotelreservaties.csv
 * ------------------------------------------------------------------------
 *
 * Twee kolommen en het antwoord, letterlijk uit het bestand van Oefening 2:
 *   x  "aantal dagen tussen reservatie en boeking"  (kolom 8)
 *   y  "gemiddelde kamerprijs"                      (kolom 16)
 *   "status boeking": Canceled = afgezegd, Not_Canceled = niet afgezegd
 * Waarom deze twee: de les vindt zelf "aantal dagen tussen reservatie en
 * boeking" het vaakst bovenaan de bomen (2132745), en de kamerprijs zat in 10
 * van 10 standaardbossen in de top 4. Wijn in 2D is onbruikbaar: 6 klassen, en
 * het beste paar geeft boom 55,5% tegen bos 58,6%. (Die drie getallen komen uit
 * de leesronde van les 6 op 2026-09-30, niet uit dit bestand.)
 *
 * Gekozen met `numpy.random.default_rng(0).permutation(36275)`: de eerste 200
 * rijen zijn de train set op het bord, de volgende 2000 een controlegroep die
 * nergens getekend wordt. De twee overlappen niet; dat wordt hieronder bij het
 * laden nagekeken (de les van Data-dokter: een "achtergehouden" rij stond daar
 * ooit ook op het bord). De rijen staan hier als tabel en niet als generator,
 * zodat elke beamer dezelfde 200 punten toont. 64 van de 200 zijn afgezegd.
 *
 * ------------------------------------------------------------------------
 * WAAROM KLEINE BOMEN, EN WAT DAT KOST (gemeten, Python 3.11, sklearn 1.6.1)
 * ------------------------------------------------------------------------
 *
 * Niels bij les 5: "Why dont I see a decision tree?". Een volle boom op 200
 * rijen heeft 42 tot 55 bladeren; die kan je niet tekenen in een tegeltje.
 * Daarom groeit elke boom hier tot hoogstens MAX_BLADEREN = 5 bladeren - zo
 * groot als de bomen op de prent van 2132681 (3 tot 5 bladeren).
 *
 * Dat heeft een prijs, en die staat hier zodat niemand de oude bewering terug
 * op het bord zet. Met VOLLE bomen wint een stemming van 15 bomen van één volle
 * boom in 99 van 100 seeds. Met bomen van 5 bladeren wint een stemming van 9
 * bomen van één boom van 5 bladeren op alle 200 rijen maar in 64 van 100. Het
 * bord beweert dus NERGENS dat het bos beter is dan één boom. Het toont hoe het
 * bos beslist: dat is het mechanisme, en dat is wat een bord moet uitleggen.
 *
 * Wat wel stevig is, gemeten op DEZE code (node, 200 waarden van BASIS):
 * - de stemming van 9 bomen heeft meer rijen van de controlegroep juist dan de
 *   helft van haar eigen bomen: 199 van 200; bij 5 bomen 197 van 200;
 * - maar een stemming verslaat niet elk van haar bomen: bij 9 bomen 84 van 200;
 * - twee bomen erbij maakt het bos soms slechter: 247 van 800 stappen. Het bord
 *   zegt dus nooit "elke boom erbij helpt";
 * - twee bomen zijn het oneens over 17,5% van de controlegroep (mediaan). Dat
 *   is genoeg om bij het slepen verschillende stemmen te zien;
 * - een boom krijgt 113 tot 141 verschillende rijen (mediaan 127) uit zijn 200
 *   trekkingen: ongeveer een derde ziet hij nooit, sommige ziet hij twee keer;
 * - bij een even aantal bomen staat het vaak gelijk. Het bord toont dat eerlijk
 *   als "gelijk" en kiest geen winnaar.
 * Geen van die getallen staat als tekst op het bord: het bord toont alleen
 * tellingen die het zelf uit zijn toestand rekent. De controlegroep en
 * `juistVanBoom` / `juistVanBos` staan hier dus NIET voor het bord, maar zodat
 * elk getal hierboven op deze code na te meten blijft.
 *
 * DE SPLITSINGSZOEKER IS NAGEKEKEN TEGEN sklearn. Met beide kenmerken toegelaten
 * gaf `maakBoom` voor boom 1 tot 20 precies dezelfde condities als
 * `DecisionTreeClassifier(max_leaf_nodes=5).fit(X, y, sample_weight=getrokken)`:
 * 20 van 20 bomen, verschil alleen in de float32-afronding van sklearn. Het
 * willekeurige kenmerk per vakje is daarna dezelfde regel als in sklearn, maar
 * met de eigen toevalsgenerator van dit project, dus bit voor bit hetzelfde bos
 * als een notebook geeft het niet - dat kan geen enkel bord.
 */

