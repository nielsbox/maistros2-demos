/** De twee kenmerken die het bord gebruikt, met hun kolomnaam uit hotelreservaties.csv. */
export const DAGEN = 0
export const PRIJS = 1
export type Kenmerk = typeof DAGEN | typeof PRIJS

export type Rij = {
  dagen: number
  prijs: number
  afgezegd: boolean
  /** Het rijnummer in hotelreservaties.csv, 1 = de eerste rij na de header. */
  nr: number
}

function uitPlat(plat: readonly number[]): Rij[] {
  const rijen: Rij[] = []
  for (let i = 0; i + 3 < plat.length; i += 4) {
    rijen.push({ dagen: plat[i], prijs: plat[i + 1], afgezegd: plat[i + 2] === 1, nr: plat[i + 3] })
  }
  return rijen
}

/** De train set: de 200 rijen die op het bord staan. */
export const TRAIN: readonly Rij[] = uitPlat(TRAIN_PLAT)

/** De controlegroep: 2000 andere rijen uit hetzelfde bestand. Nooit getekend,
 *  nooit aanklikbaar. */
export const CONTROLE: readonly Rij[] = uitPlat(CONTROLE_PLAT)

/* De controlegroep mag nooit een rij van het bord bevatten. Gecontroleerd op
   rijnummer, niet op waarden: rijen met dezelfde waarden komen in het bestand
   echt meer dan één keer voor. Dit draait altijd, ook in de klas: een bord dat
   hier faalt, rekent met data die het niet mag gebruiken. */
{
  const opBord = new Set(TRAIN.map((r) => r.nr))
  const overlap = CONTROLE.filter((r) => opBord.has(r.nr)).length
  if (TRAIN.length !== 200 || CONTROLE.length !== 2000 || opBord.size !== 200 || overlap > 0) {
    throw new Error(
      `bos.ts: train set ${TRAIN.length} (${opBord.size} verschillend), controlegroep ${CONTROLE.length}, overlap ${overlap}`,
    )
  }
}

export const waardeVan = (r: { dagen: number; prijs: number }, k: Kenmerk): number =>
  k === DAGEN ? r.dagen : r.prijs

/** Hoeveel bomen het bos hoogstens krijgt. */
export const MAX_BOMEN = 9

/** Hoeveel bladeren een boom hoogstens krijgt. */
export const MAX_BLADEREN = 5

/** Het vaste startgetal van de toevalsgenerator. */
export const BASIS = 0

/* ------------------------------ de boom ------------------------------ */

export type Blad = {
  soort: 'blad'
  afgezegd: boolean
  /** Gewicht niet afgezegd, gewicht afgezegd: een rij die twee keer getrokken is telt twee keer. */
  telling: [number, number]
}

export type Vakje = {
  soort: 'vakje'
  kenmerk: Kenmerk
  drempel: number
  waar: Knoop
  vals: Knoop
  telling: [number, number]
}

export type Knoop = Blad | Vakje

export type Boom = {
  /** 1, 2, 3, ... zoals op de prent van de les. */
  nr: number
  /** Per rij van TRAIN: hoe vaak de boom die rij getrokken heeft. 0 = nooit gezien. */
  getrokken: readonly number[]
  /** Hoeveel verschillende rijen de boom gezien heeft. */
  gezien: number
  wortel: Knoop
}

function telVan(ids: readonly number[], w: readonly number[]): [number, number] {
  let niet = 0
  let af = 0
  for (const i of ids) {
    if (TRAIN[i].afgezegd) af += w[i]
    else niet += w[i]
  }
  return [niet, af]
}

/** Gini maal gewicht: hoe gemengd een vakje is, in rijen uitgedrukt. */
function onzuiverheid([niet, af]: [number, number]): number {
  const n = niet + af
  if (n === 0) return 0
  return n - (niet * niet + af * af) / n
}

type Kandidaat = { kenmerk: Kenmerk; drempel: number; winst: number }

/** De beste drempel op één kenmerk: midden tussen twee waarden die echt voorkomen. */
function besteOp(ids: readonly number[], w: readonly number[], k: Kenmerk): Kandidaat | null {
  const gesorteerd = [...ids].sort((a, b) => waardeVan(TRAIN[a], k) - waardeVan(TRAIN[b], k))
  const totaal = telVan(ids, w)
  const voor = onzuiverheid(totaal)
  let links: [number, number] = [0, 0]
  let beste: Kandidaat | null = null
  for (let j = 0; j < gesorteerd.length - 1; j++) {
    const r = TRAIN[gesorteerd[j]]
    if (r.afgezegd) links = [links[0], links[1] + w[gesorteerd[j]]]
    else links = [links[0] + w[gesorteerd[j]], links[1]]
    const a = waardeVan(r, k)
    const b = waardeVan(TRAIN[gesorteerd[j + 1]], k)
    if (a === b) continue
    const rechts: [number, number] = [totaal[0] - links[0], totaal[1] - links[1]]
    const winst = voor - onzuiverheid(links) - onzuiverheid(rechts)
    // Bij gelijke winst wint de kleinste drempel: vaste volgorde, dus elke
    // beamer ziet dezelfde boom.
    if (!beste || winst > beste.winst + 1e-9) beste = { kenmerk: k, drempel: (a + b) / 2, winst }
  }
  return beste
}

/**
 * Welke conditie een vakje krijgt. Zoals `RandomForestClassifier` met twee
 * kenmerken (`max_features='sqrt'` wordt 1): het vakje trekt EEN kenmerk en zoekt
 * alleen daarop de beste drempel. Heeft dat kenmerk in dit vakje maar één
 * waarde, dan neemt het het andere.
 */
function kandidaatVoor(
  ids: readonly number[],
  w: readonly number[],
  rnd: () => number,
): Kandidaat | null {
  const eerst: Kenmerk = rnd() < 0.5 ? DAGEN : PRIJS
  const dan: Kenmerk = eerst === DAGEN ? PRIJS : DAGEN
  const k = besteOp(ids, w, eerst) ?? besteOp(ids, w, dan)
  if (!k || k.winst <= 1e-9) return null
  return k
}

function maakBlad(t: [number, number]): Blad {
  // Bij een gelijke stand zegt het blad "niet afgezegd". Vaste keuze.
  return { soort: 'blad', afgezegd: t[1] > t[0], telling: t }
}

/** Een toevalsgenerator per boom. `seeded` is een LCG: twee startgetallen die
 *  één verschillen, geven een bijna gelijk eerste getal. Daarom een grote stap
 *  tussen de bomen en acht getallen weggooien voor het echte werk begint. */
function generatorVoor(nr: number): () => number {
  const rnd = seeded(BASIS + nr * 1000003)
  for (let i = 0; i < 8; i++) rnd()
  return rnd
}

/**
 * Maak boom `nr`. Twee keer toeval, en verder niets:
 * 1. 200 keer een willekeurige rij uit de train set trekken, met teruglegging;
 * 2. per vakje één willekeurig kenmerk.
 * Daarna groeit de boom zoals in les 5: telkens de splitsing die het meest
 * helpt, tot hij MAX_BLADEREN bladeren heeft of niets meer helpt.
 */
export function maakBoom(nr: number): Boom {
  const rnd = generatorVoor(nr)
  const w = new Array<number>(TRAIN.length).fill(0)
  for (let i = 0; i < TRAIN.length; i++) w[Math.floor(rnd() * TRAIN.length) % TRAIN.length]++
  const alle = TRAIN.map((_, i) => i).filter((i) => w[i] > 0)

  type Open = { ids: number[]; kandidaat: Kandidaat | null; volgorde: number; zet: (k: Knoop) => void }
  let wortel: Knoop = maakBlad(telVan(alle, w))
  let teller = 0
  const open: Open[] = [
    { ids: alle, kandidaat: kandidaatVoor(alle, w, rnd), volgorde: teller++, zet: (k) => (wortel = k) },
  ]
  let bladeren = 1
  while (bladeren < MAX_BLADEREN) {
    let keuze = -1
    for (let j = 0; j < open.length; j++) {
      const k = open[j].kandidaat
      if (!k) continue
      if (keuze < 0 || k.winst > open[keuze].kandidaat!.winst + 1e-9) keuze = j
    }
    if (keuze < 0) break
    const o = open.splice(keuze, 1)[0]
    const c = o.kandidaat!
    const links = o.ids.filter((i) => waardeVan(TRAIN[i], c.kenmerk) <= c.drempel)
    const rechts = o.ids.filter((i) => waardeVan(TRAIN[i], c.kenmerk) > c.drempel)
    const vakje: Vakje = {
      soort: 'vakje',
      kenmerk: c.kenmerk,
      drempel: c.drempel,
      waar: maakBlad(telVan(links, w)),
      vals: maakBlad(telVan(rechts, w)),
      telling: telVan(o.ids, w),
    }
    o.zet(vakje)
    open.push({ ids: links, kandidaat: kandidaatVoor(links, w, rnd), volgorde: teller++, zet: (k) => (vakje.waar = k) })
    open.push({ ids: rechts, kandidaat: kandidaatVoor(rechts, w, rnd), volgorde: teller++, zet: (k) => (vakje.vals = k) })
    bladeren++
  }
  return { nr, getrokken: w, gezien: alle.length, wortel }
}

/* ------------------------------ stemmen ------------------------------ */

export type Stap = 'waar' | 'vals'

/** Wat een boom zegt over één boeking, en langs welke weg hij daar komt. */
export function stemVan(boom: Boom, b: { dagen: number; prijs: number }): { afgezegd: boolean; pad: Stap[] } {
  const pad: Stap[] = []
  let k = boom.wortel
  while (k.soort === 'vakje') {
    if (waardeVan(b, k.kenmerk) <= k.drempel) {
      pad.push('waar')
      k = k.waar
    } else {
      pad.push('vals')
      k = k.vals
    }
  }
  return { afgezegd: k.afgezegd, pad }
}

export type Uitslag = { afgezegd: number; niet: number; bos: 'afgezegd' | 'niet afgezegd' | 'gelijk' }

/** De stemming van het bos over één boeking: de meeste stemmen winnen. */
export function stemming(bomen: readonly Boom[], b: { dagen: number; prijs: number }): Uitslag {
  let af = 0
  for (const boom of bomen) if (stemVan(boom, b).afgezegd) af++
  const niet = bomen.length - af
  return { afgezegd: af, niet, bos: af > niet ? 'afgezegd' : niet > af ? 'niet afgezegd' : 'gelijk' }
}

/** Hoeveel rijen van de controlegroep één boom juist heeft. */
export function juistVanBoom(boom: Boom): number {
  let n = 0
  for (const r of CONTROLE) if (stemVan(boom, r).afgezegd === r.afgezegd) n++
  return n
}

/** Hoeveel rijen van de controlegroep het bos juist heeft, en bij hoeveel het gelijk staat. */
export function juistVanBos(bomen: readonly Boom[]): { juist: number; gelijk: number } {
  let juist = 0
  let gelijk = 0
  for (const r of CONTROLE) {
    const u = stemming(bomen, r).bos
    if (u === 'gelijk') gelijk++
    else if ((u === 'afgezegd') === r.afgezegd) juist++
  }
  return { juist, gelijk }
}

/* ------------------------------ kaarten ------------------------------ */

export type Gebied = { x0: number; x1: number; y0: number; y1: number }
export type KaartVak = Gebied & { uitslag: 'afgezegd' | 'niet afgezegd' | 'gelijk' }

/** De vakjes van één boom als rechthoeken in het vlak (dagen, prijs). */
export function kaartVanBoom(boom: Boom, g: Gebied): KaartVak[] {
  const uit: KaartVak[] = []
  const loop = (k: Knoop, r: Gebied) => {
    if (r.x1 <= r.x0 || r.y1 <= r.y0) return
    if (k.soort === 'blad') {
      uit.push({ ...r, uitslag: k.afgezegd ? 'afgezegd' : 'niet afgezegd' })
      return
    }
    if (k.kenmerk === DAGEN) {
      loop(k.waar, { ...r, x1: Math.min(r.x1, k.drempel) })
      loop(k.vals, { ...r, x0: Math.max(r.x0, k.drempel) })
    } else {
      loop(k.waar, { ...r, y1: Math.min(r.y1, k.drempel) })
      loop(k.vals, { ...r, y0: Math.max(r.y0, k.drempel) })
    }
  }
  loop(boom.wortel, g)
  return uit
}

function drempelsVan(k: Knoop, kenmerk: Kenmerk, uit: Set<number>) {
  if (k.soort === 'blad') return
  if (k.kenmerk === kenmerk) uit.add(k.drempel)
  drempelsVan(k.waar, kenmerk, uit)
  drempelsVan(k.vals, kenmerk, uit)
}

/** De kaart van het bos: elk stuk van het vlak krijgt de uitslag van de stemming daar.
 *  Exact, geen raster: tussen twee opeenvolgende drempels verandert geen enkele boom. */
export function kaartVanBos(bomen: readonly Boom[], g: Gebied): KaartVak[] {
  const xs = new Set<number>()
  const ys = new Set<number>()
  for (const b of bomen) {
    drempelsVan(b.wortel, DAGEN, xs)
    drempelsVan(b.wortel, PRIJS, ys)
  }
  const xr = [g.x0, ...[...xs].filter((x) => x > g.x0 && x < g.x1).sort((a, b) => a - b), g.x1]
  const yr = [g.y0, ...[...ys].filter((y) => y > g.y0 && y < g.y1).sort((a, b) => a - b), g.y1]
  const uit: KaartVak[] = []
  for (let j = 0; j < yr.length - 1; j++) {
    let begin = 0
    let vorige: KaartVak['uitslag'] | null = null
    for (let i = 0; i < xr.length - 1; i++) {
      const u = stemming(bomen, { dagen: (xr[i] + xr[i + 1]) / 2, prijs: (yr[j] + yr[j + 1]) / 2 }).bos
      if (vorige !== null && u !== vorige) {
        uit.push({ x0: xr[begin], x1: xr[i], y0: yr[j], y1: yr[j + 1], uitslag: vorige })
        begin = i
      }
      vorige = u
    }
    if (vorige !== null) uit.push({ x0: xr[begin], x1: xr[xr.length - 1], y0: yr[j], y1: yr[j + 1], uitslag: vorige })
  }
  return uit
}

/** Alle knopen van een boom met hun pad, voor de tekening. */
export function knopenVan(k: Knoop, pad: Stap[] = []): { pad: Stap[]; knoop: Knoop }[] {
  if (k.soort === 'blad') return [{ pad, knoop: k }]
  return [{ pad, knoop: k }, ...knopenVan(k.waar, [...pad, 'waar']), ...knopenVan(k.vals, [...pad, 'vals'])]
}

export function diepteVan(k: Knoop): number {
  return k.soort === 'blad' ? 0 : 1 + Math.max(diepteVan(k.waar), diepteVan(k.vals))
}

export function bladerenVan(k: Knoop): number {
  return k.soort === 'blad' ? 1 : bladerenVan(k.waar) + bladerenVan(k.vals)
}
